export function getSubjectById(subjectId: string, customSubjects: Subject[] = DEFAULT_ALL_SUBJECTS): Subject | undefined {
  return customSubjects.find((s) => s.id === subjectId);
}

export function getTopicById(topicId: string, customSubjects: Subject[] = DEFAULT_ALL_SUBJECTS): Topic | undefined {
  for (const s of customSubjects) {
    const found = s.topics.find((t) => t.id === topicId);
    if (found) return found;
  }
  return undefined;
}
